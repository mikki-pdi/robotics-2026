/**
 * Initialise the SSD1306 OLED display. This requires that the I2C has already been initialised.
 */
void YEEP144_SSD1306_Init(void){

	// Allocate space in memory for the framebuffer to be stored
	// As the display is monochrome we only need 1 bit per pixel, so the data is packed
	// to save on memory space - i.e. 8 pixels per byte
	// The arithmetic used ensures that the buffer size is always padded to a whole byte number
	//
	// This is also how the framebuffer is stored within the OLED chip, so it can be directly
	// copied across without additional manipulation
	//
	// We make the TX buffer 1 byte larger than needed for the display data so the value 0x40 can be prepended
	// When it comes time to send the framebuffer to the display, that initial byte is required so the data is treated
	// as display data, not commands
	displayTXBuffer = (uint8_t *)malloc((WIDTH * ((HEIGHT + 7) / 8)) + 1);
	displayTXBuffer[0] = 0x40;

	// For programming ease we store a separate pointer offset by 1 to directly access the display data portion of the buffer
	displayBuffer = displayTXBuffer + 1;
	
	// Ensure the display buffer is empty
	YEEP144_SSD1306_ClearDisplay();

	// This list of commands sets up the display and turns it on
	uint8_t initCommandList[] = {
		0x00, // Tell the display these are commands not graphics data
		SSD1306_DISPLAYOFF,
		SSD1306_SETDISPLAYCLOCKDIV,
		0x80, // Recommended clock div
		SSD1306_SETMULTIPLEX,
		HEIGHT - 1,
		SSD1306_SETDISPLAYOFFSET,
		0x0, // No display offset
		SSD1306_SETSTARTLINE | 0x0, // Start at line 0
		SSD1306_CHARGEPUMP,
		0x14, // Enable internal charge pump
		SSD1306_MEMORYMODE,
		0x00,
		SSD1306_SEGREMAP | 0x1,
		SSD1306_COMSCANDEC,
		SSD1306_SETCOMPINS,
		0x02, // This is hardcoded for the value for a 128x32 screen
		SSD1306_SETCONTRAST,
		0x8F, // This is hardcoded for the value for a 128x32 screen
		SSD1306_SETPRECHARGE,
		0xF1, // Value for when charge pump is enabled
		SSD1306_SETVCOMDETECT,
		0x40,
		SSD1306_DISPLAYALLON_RESUME,
		SSD1306_NORMALDISPLAY,
		SSD1306_DEACTIVATE_SCROLL,
		SSD1306_DISPLAYON

	};

	// Send the commands
	HAL_I2C_Master_Transmit(&hi2c2, SSD1306_ADDR, initCommandList, sizeof(initCommandList), I2C_TIMEOUT);

}

/**
 * Update the display by transfering the contents of the display buffer to the display.
 * No changes to the displayed graphics will be made until this command is called
 */
void YEEP144_SSD1306_Display(void){
	// Before sending graphics data we need to define where the data goes
	// As we are always copying over the whole frame buffer, we want our transfer to fill
	// the whole graphics memory on the driver chip
	uint8_t commandList[] = {
		0x00,               // Following data are commands
		SSD1306_PAGEADDR,
		0,                  // Starting page
		0xFF,               // Ending page
		SSD1306_COLUMNADDR,
		0,                  // Starting column
		(WIDTH-1),          // Ending column
		//0x40                // Following data will be graphics not commands
	};

	// Send these commands
	HAL_I2C_Master_Transmit(&hi2c2, SSD1306_ADDR, commandList, sizeof(commandList), I2C_TIMEOUT);

	// Send the graphics data. We use the TXbuffer here so it includes the additional byte at the start that tells the chip this is graphics data
	HAL_I2C_Master_Transmit(&hi2c2, SSD1306_ADDR, displayTXBuffer, (WIDTH * ((HEIGHT + 7) / 8)) + 1, I2C_TIMEOUT);

}

/**
 * Clears the display by clearing the display buffer
 */
void YEEP144_SSD1306_ClearDisplay(void){

	// Clear the display by filling the buffer with all zeros
	memset(displayBuffer, 0, WIDTH * ((HEIGHT + 7) / 8));
}

/**
 * Sets a single pixel in the display buffer to the specified colour
 */
void YEEP144_SSD1306_SetPixel(uint8_t x, uint8_t y, uint8_t colour){

	// As the data is packed with 8 pixels per byte, we need to do some bit-level
	// manipulation to set an individual pixel
	switch(colour){
		// Set the bit for white (on)
		case SSD1306_WHITE:
			displayBuffer[x + (y / 8) * WIDTH] |= (1 << (y & 7));
			break;
		// Clear the bit for black (off)
		case SSD1306_BLACK:
			displayBuffer[x + (y / 8) * WIDTH] &= ~(1 << (y & 7));
			break;
		// Invert the bit to invert the colour
		case SSD1306_INVERSE:
			displayBuffer[x + (y / 8) * WIDTH] ^= (1 << (y & 7));
			break;
	}
}

/**
 * Returns the current value of the specified pixel from the display buffer.
 * Note that this is what is currently stored in the local buffer, not
 * necessarily what is currently being displayed if Display has not been called
 */
bool YEEP144_SSD1306_GetPixel(uint8_t x, uint8_t y){
	// As the 1-bit pixels are packed into bytes, we need to do some bit manipulation to retrieve the individual bit
	return (displayBuffer[x + (y / 8) * WIDTH] & (1 << (y & 7)));
}

/**
 * Draws a line between the specified coordinates, using the specified colour
 */
void YEEP144_SSD1306_DrawLine(uint8_t x0, uint8_t y0, uint8_t x1, uint8_t y1, uint8_t colour){
	// This function checks if the draw can be fufilled by one of the optimised horizontal or vertical
	// line drawing functions, if not passes to the generalised one
	if(x0 == x1){ // If both x coordinates are the same then this is vertical
		if (y0 > y1){ // Normalise direction by swapping the coords if needed
			uint8_t t = y0;
			y0 = y1;
			y1 = t;
		}
		YEEP144_SSD1306_DrawFastVLine(x0, y0, y1 - y0, colour);
	}
	else if(y0 == y1){ // If both y coordinates are the same then this is horizontal
		if(x0 > x1){ // Normalise direction by swapping the coords if needed
			uint8_t t = x0;
			x0 = x1;
			x1 = t;
		}
		YEEP144_SSD1306_DrawFastHLine(x0, y0, x1 - x0, colour);
	}
	else{
		// If this cannot be handled by either of the fast algorithms, fallback to the general one
		YEEP144_SSD1306_DrawLineInternal(x0, y0, x1, y1, colour);
	}
}

/**
 * Draws a line between the two specified points using Bresenham's algorithm
 * This is only used when the line is not vertical or horizontal
 * This will only be an approximation of requested line due to the limited resolution of the display
 * and the lack of options for antialiasing
 */
void YEEP144_SSD1306_DrawLineInternal(uint8_t x0, uint8_t y0, uint8_t x1, uint8_t y1, uint8_t colour){
	// Bresenham's algorithm only works when going in the positive direction, which would be down and right
	// for a display with (0,0) in the top left corner. So that this can be used for all cases, 
	// we need to detect the direction of the requested line and transform the coordinates
	uint8_t steep = abs(y1 - y0) > abs(x1 - x0);

	if(steep){
		uint8_t t = x0;
		x0 = y0;
		y0 = t;

		t = x1;
		x1 = y1;
		y1 = t;
	}

	if(x0 > x1){
		uint8_t t = x0;
		x0 = x1;
		x1 = t;
		t = y0;
		y0 = y1;
		y1 = t;
	}

	int8_t dx = x1 - x0;
	int8_t dy = abs(y1 - y0);

	int8_t err = dx / 2;
	int8_t ystep;

	if(y0 < y1){
		ystep = 1;
	}
	else{
		ystep = -1;
	}

	for(; x0 <= x1; x0++){
		if(steep){
			YEEP144_SSD1306_SetPixel(y0, x0, colour);
		}
		else{
			YEEP144_SSD1306_SetPixel(x0, y0, colour);
		}
		err -= dy;
		if(err < 0){
			y0 += ystep;
			err += dx;
		}
	}
}

/**
 * Draw a purely horizontal line. This is faster than the general algorithm,
 * but only works for horizontal lines
 */
void YEEP144_SSD1306_DrawFastHLine(uint8_t x, uint8_t y, int8_t w, uint8_t colour){
	if (y < HEIGHT) { // Y coord in bounds?
		if ((x + w) > WIDTH) { // Clip right
			w = (WIDTH - x);
		}
		if (w > 0) { // Proceed only if width is positive
			uint8_t *pBuf = &displayBuffer[(y / 8) * WIDTH + x];
			uint8_t mask = 1 << (y & 7);
			switch (colour) {
				case SSD1306_WHITE:
					while (w--) {
						*pBuf++ |= mask;
					};
					break;
				case SSD1306_BLACK:
					mask = ~mask;
					while (w--) {
						*pBuf++ &= mask;
					};
					break;
				case SSD1306_INVERSE:
					while (w--) {
						*pBuf++ ^= mask;
					};
					break;
			}
		}
	}
}

/**
 * Draw a purely vertical line. This is faster than the general algorithm,
 * but only works for vertical lines
 */
void YEEP144_SSD1306_DrawFastVLine(uint8_t x, uint8_t y, int8_t h, uint8_t colour){
	if (x < WIDTH) { // X coord in bounds?
		if ((y + h) > HEIGHT) { // Clip bottom
			h = (HEIGHT - y);
		}
		if (h > 0) { // Proceed only if height is now positive
			
			uint8_t *pBuf = &displayBuffer[(y / 8) * WIDTH + x];
			
			// do the first partial byte, if necessary - this requires some masking
			uint8_t mod = (y & 7);
			if (mod) {
				// mask off the high n bits we want to set
				mod = 8 - mod;
				// note - lookup table results in a nearly 10% performance
				// improvement in fill* functions
				// uint8_t mask = ~(0xFF >> mod);
				static const uint8_t premask[8] = {0x00, 0x80, 0xC0, 0xE0,
					0xF0, 0xF8, 0xFC, 0xFE};
				uint8_t mask = premask[mod];
				// adjust the mask if we're not going to reach the end of this byte
				if (h < mod)
				mask &= (0XFF >> (mod - h));
				
				switch (colour) {
					case SSD1306_WHITE:
					*pBuf |= mask;
					break;
					case SSD1306_BLACK:
					*pBuf &= ~mask;
					break;
					case SSD1306_INVERSE:
					*pBuf ^= mask;
					break;
				}
				pBuf += WIDTH;
			}
			
			if (h >= mod) { // More to go?
				h -= mod;
				// Write solid bytes while we can - effectively 8 rows at a time
				if (h >= 8) {
					if (colour == SSD1306_INVERSE) {
						// separate copy of the code so we don't impact performance of
						// black/white write version with an extra comparison per loop
						do {
							*pBuf ^= 0xFF; // Invert byte
							pBuf += WIDTH; // Advance pointer 8 rows
							h -= 8;        // Subtract 8 rows from height
						} while (h >= 8);
					} else {
						// store a local value to work with
						uint8_t val = (colour != SSD1306_BLACK) ? 255 : 0;
						do {
							*pBuf = val;   // Set byte
							pBuf += WIDTH; // Advance pointer 8 rows
							h -= 8;        // Subtract 8 rows from height
						} while (h >= 8);
					}
				}
				
				if (h) { // Do the final partial byte, if necessary
					mod = h & 7;
					// this time we want to mask the low bits of the byte,
					// vs the high bits we did above
					// uint8_t mask = (1 << mod) - 1;
					// note - lookup table results in a nearly 10% performance
					// improvement in fill* functions
					static const uint8_t postmask[8] = {0x00, 0x01, 0x03, 0x07,
						0x0F, 0x1F, 0x3F, 0x7F};
					uint8_t mask = postmask[mod];
					switch (colour) {
						case SSD1306_WHITE:
						*pBuf |= mask;
						break;
						case SSD1306_BLACK:
						*pBuf &= ~mask;
						break;
						case SSD1306_INVERSE:
						*pBuf ^= mask;
						break;
					}
				}
			}
		} // endif positive height
	} // endif x in bounds
}

/**
 * Draws an outline of a rectangle with no fill. Coordinates represent the top left corner
 */
void YEEP144_SSD1306_DrawRect(uint8_t x, uint8_t y, uint8_t w, uint8_t h, uint8_t colour){
	YEEP144_SSD1306_DrawFastHLine(x, y, w, colour);
	YEEP144_SSD1306_DrawFastHLine(x, y + h - 1, w, colour);
	YEEP144_SSD1306_DrawFastVLine(x, y, h, colour);
	YEEP144_SSD1306_DrawFastVLine(x + w - 1, y, h, colour);
}

/**
 * Draw a filled rectangle of given width and height, with the top left corner specified
 * by the given coordinates
 */
void YEEP144_SSD1306_DrawFillRect(uint8_t x, uint8_t y, int8_t w, int8_t h, uint8_t colour){
	for (int16_t i = x; i < x + w; i++) {
		YEEP144_SSD1306_DrawFastVLine(i, y, h, colour);
	}
}

/**
 * Prints text to the screen using printf-style formatting. Cursor starting position, font size and
 * text wrapping can be controlled using the provided functions
 */
int YEEP144_SSD1306_printf(const char * format, ...){
	// Set the buffer size to the maximum that can fit on the screen with the smallest font
    size_t bufSize = MAXCHAR;

    // Try to allocate that buffer
    char* buffer = malloc(bufSize);

    // If the buffer cannot be allocated, return -1
    if (buffer == NULL) return -1;

    // Get the pointer to the variadic args
    va_list args;
    va_start (args, format);

    // Create our final string in the buffer using vsnprintf, passing through our argument pointer
    vsnprintf(buffer, bufSize, format, args);

    // Calulate the final size of the string
    bufSize = strlen(buffer);

	// Write our characters one by one to the screen
	for(size_t i = 0; i < bufSize; i++){
		char c = buffer[i];

		if(c == '\n'){// Newline - move cursor down by 1 line, and back to start of line
			cursorX = 0;
			cursorY += textSize * (FONTHEIGHT + 1);
		}
		else if(c != '\r'){ // All other text - ignoring carriage returns
			if(textWrap && ((cursorX + textSize * (FONTWIDTH + 1)) > WIDTH)){
				// If wrapping is enabled and this character will overflow the display, move to start of next line
				cursorX = 0;
				cursorY += textSize * (FONTHEIGHT + 1);
			}
			if((cursorY + FONTHEIGHT) > HEIGHT){ // If we have reached the bottom of the screen, start back at the top
				cursorY = 0;
				cursorX = 0;
			}
			// Draw the character at the cursor coordinates
			YEEP144_SSD1306_DrawChar(cursorX, cursorY, c, textColour, textBGColour, textSize);

			// Move the cursor forward by one character
			cursorX += (FONTWIDTH + 1) * textSize;
		}
	}

    // Free the memory used
    free(buffer);

    // Return number of characters printed
    return bufSize;
}

/**
 * Draws a single character to the screen, with the specified coordinates being the top left of the character
 * Uses the specified text colour, background colour and size multiplier
 */
void YEEP144_SSD1306_DrawChar(uint8_t x, uint8_t y, uint8_t c, uint8_t colour, uint8_t bg, uint8_t size){
	
	if ((x >= WIDTH) ||              // Clip right
		(y >= HEIGHT) ||             // Clip bottom
		((x + 6 * size - 1) < 0) || // Clip left
		((y + 8 * size - 1) < 0))   // Clip top
	return;
	
	for (int8_t i = 0; i < 5; i++) { // Char bitmap = 5 columns
		uint8_t line = font[c * 5 + i];
		for (int8_t j = 0; j < 8; j++, line >>= 1) {
			if (line & 1) {
				if (size == 1)
					YEEP144_SSD1306_SetPixel(x + i, y + j, colour);
				else
					YEEP144_SSD1306_DrawFillRect(x + i * size, y + j * size, size, size, colour);
			} else if (bg != colour) {
				if (size == 1)
					YEEP144_SSD1306_SetPixel(x + i, y + j, bg);
				else
					YEEP144_SSD1306_DrawFillRect(x + i * size, y + j * size, size, size, bg);
			}
		}
	}
	if (bg != colour) { // If opaque, draw vertical line for last column
		if (size == 1)
			YEEP144_SSD1306_DrawFastVLine(x + 5, y, 8, bg);
		else
			YEEP144_SSD1306_DrawFillRect(x + 5 * size, y, size, 8 * size, bg);
	}
}

