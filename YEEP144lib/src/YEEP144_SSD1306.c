/**
 * Draws a 1-bit bitmap to the screen at the specified position
 */
void YEEP144_SSD1306_DrawBitmap(uint8_t x, uint8_t y, const uint8_t bitmap[], uint8_t w, uint8_t h){
	uint8_t byteWidth = (w + 7) / 8; // Bitmap scanline pad = whole byte
	uint8_t b = 0;

	for (uint8_t j = 0; j < h; j++, y++) {
		for (uint8_t i = 0; i < w; i++) {
			if (i & 7){
				b <<= 1;
			}
			else{
				b = bitmap[j * byteWidth + i / 8];
			}
			YEEP144_SSD1306_SetPixel(x + i, y, (b & 0x80) ? SSD1306_WHITE : SSD1306_BLACK);
		}
	}
}

/**
 * Inverts the colours of the display. Note that this happens using a hardware command to the display
 * and doesn't touch the buffer
 */
void YEEP144_SSD1306_InvertDisplay(bool i){
	YEEP144_SSD1306_SendCommand(i ? SSD1306_INVERTDISPLAY : SSD1306_NORMALDISPLAY);
}

/**
 * Helper function that sends a single command to the display
 */
void YEEP144_SSD1306_SendCommand(uint8_t command){

	// For data to be recognised as a command, the I2C transaction must start with 0x00
	uint8_t data[] = {0x00, command};

	// Transmit the data
	HAL_I2C_Master_Transmit(&hi2c2, SSD1306_ADDR, data, 2, I2C_TIMEOUT);
}

